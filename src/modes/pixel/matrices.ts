/**
 * Normalizes Arabic letters to base form.
 */
export function normalizeArabicChar(char: string): string {
  const map: Record<string, string> = {
    أ: 'ا',
    إ: 'ا',
    آ: 'ا',
    ٱ: 'ا',
    ة: 'ه',
    ى: 'ي',
    ؤ: 'و',
    ئ: 'ي',
    ء: 'ا',
  };
  return map[char] || char;
}

/**
 * Retrieves the base glyph matrix for a character.
 * Defaults to 7x7 when available, otherwise 5x5.
 */
export function getGlyphMatrix(char: string, preferredSize: number = 7): { matrix: GlyphMatrix; baseSize: number } | null {
  const normChar = normalizeArabicChar(char.toLocaleUpperCase());

  if (preferredSize <= 5) {
    if (LATIN_5X5[normChar]) return { matrix: LATIN_5X5[normChar], baseSize: 5 };
    if (ARABIC_5X5[normChar]) return { matrix: ARABIC_5X5[normChar], baseSize: 5 };
  } else {
    if (LATIN_7X7[normChar]) return { matrix: LATIN_7X7[normChar], baseSize: 7 };
    if (ARABIC_7X7[normChar]) return { matrix: ARABIC_7X7[normChar], baseSize: 7 };
    // Fallback to 5x5 if 7x7 isn't found
    if (LATIN_5X5[normChar]) return { matrix: LATIN_5X5[normChar], baseSize: 5 };
    if (ARABIC_5X5[normChar]) return { matrix: ARABIC_5X5[normChar], baseSize: 5 };
  }

  return null;
}
